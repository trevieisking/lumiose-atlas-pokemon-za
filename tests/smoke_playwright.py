"""Optional local Chromium smoke checks; requires Playwright and installed browser."""
from playwright.sync_api import sync_playwright
from pathlib import Path
import json
OUT=Path('/mnt/data/lumiose-qa');OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[];failed=[]
 page.on('pageerror',lambda exc: errors.append(str(exc)))
 page.on('requestfailed',lambda req: failed.append(f'{req.url}: {req.failure}'))
 page.goto('http://localhost:8765/index.html',wait_until='domcontentloaded',timeout=30000)
 page.wait_for_timeout(700)
 print('title:',page.title())
 print('home visible:',page.locator('section#home').evaluate('(e)=>getComputedStyle(e).display'))
 page.screenshot(path=str(OUT/'home_desktop.png'),full_page=False)
 page.locator('#sideNav a[data-view="walkthrough"]').click()
 page.wait_for_timeout(150)
 print('walkthrough visible',page.locator('#walkthrough').is_visible(), 'mission cards',page.locator('#missionsList .mission').count())
 page.locator('#mission-1 [data-expand="1"]').click()
 print('mission expanded',page.locator('#mission-1').get_attribute('class'), 'body visible',page.locator('#mission-1 .mission-body').is_visible())
 page.locator('#mission-1 [data-check="1"]').check()
 print('progress after first check',page.locator('#progressText').inner_text())
 page.locator('#missionSearch').fill('The City in the Shadow')
 print('search visibility',page.locator('#missionsList .mission:visible').count())
 page.screenshot(path=str(OUT/'walkthrough_desktop.png'),full_page=False)
 page.goto('http://localhost:8765/index.html#walkthrough')
 print('progress reloaded',page.locator('#progressText').inner_text())
 page.locator('#sideNav a[data-view="maps"]').click()
 print('map view visible',page.locator('#maps').is_visible(),'map pin count',page.locator('#maps [data-select-zone]').count())
 page.locator('#atlasPins [data-select-zone="1"]').first.click()
 print('zone panel title',page.locator('#mapZoneDetail h3').inner_text())
 page.screenshot(path=str(OUT/'maps_desktop.png'),full_page=False)
 page.locator('#sideNav a[data-view="pokedex"]').click()
 page.locator('#dexSearch').fill('Chikorita')
 print('dex visible',page.locator('#dexGrid .dex-card:visible').count())
 page.screenshot(path=str(OUT/'dex_desktop.png'),full_page=False)
 page.locator('#pokedex [data-dex-source="Hyperspace"]').click()
 print('hyperspace warning',page.locator('#dexUnrecovered').is_visible())
 page.goto('http://localhost:8765/side-missions.html')
 print('stub:',page.locator('h1').inner_text())
 print('page errors',errors[:30]);print('failed requests',failed[:20]);
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
 mobile_errors=[];mobile.on('pageerror',lambda exc:mobile_errors.append(str(exc)))
 mobile.goto('http://localhost:8765/index.html',wait_until='domcontentloaded')
 mobile.screenshot(path=str(OUT/'home_mobile.png'),full_page=False)
 print('mobile nav',mobile.locator('#sideNav').is_visible(),'navigation reach',mobile.locator('#sideNav a[data-view="walkthrough"]').is_visible())
 mobile.locator('#sideNav a[data-view="walkthrough"]').click(timeout=7000)
 mobile.screenshot(path=str(OUT/'walkthrough_mobile.png'),full_page=False)
 print('mobile errors',mobile_errors)
 browser.close()
